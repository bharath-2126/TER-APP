import 'dart:io';
import 'package:path_provider/path_provider.dart';
import 'package:share_plus/share_plus.dart';

class StatementExportService {
  /// Saves bytes (PDF or CSV) to a local file in the app documents or download directory
  static Future<File> saveFileLocally({
    required List<int> bytes,
    required String fileName,
  }) async {
    final Directory directory = await getApplicationDocumentsDirectory();
    final statementsDir = Directory('${directory.path}/TER_Statements');
    if (!await statementsDir.exists()) {
      await statementsDir.create(recursive: true);
    }

    final sanitizedName = fileName.replaceAll(RegExp(r'[\\/:*?"<>| ]'), '_');
    final file = File('${statementsDir.path}/$sanitizedName');
    await file.writeAsBytes(bytes);
    return file;
  }

  /// Saves a CSV string to a local file
  static Future<File> saveCsvLocally({
    required String csvContent,
    required String fileName,
  }) async {
    return saveFileLocally(
      bytes: csvContent.codeUnits,
      fileName: fileName,
    );
  }

  /// Triggers Android's native share intent using share_plus
  static Future<void> shareFile({
    required File file,
    required String subject,
    String? text,
  }) async {
    final xFile = XFile(file.path);
    await Share.shareXFiles(
      [xFile],
      subject: subject,
      text: text ?? 'Please find attached the financial statement generated by TER (Track Every Rupee).',
    );
  }
}
